#!/usr/bin/env python3
"""Replay an existing operating-characteristics bundle through native Python MML.

The generator is intentionally out of scope: this adapter consumes byte-retained
ratings, truth, and anchors produced by ``operating_characteristics.py``.  Its
purpose is to put the application's own marginal-likelihood estimator on the
same run ledger as FACETS JMLE, TAM/sirt MML, and exact CMLE.

The two registered pilot modes separate a correct fixed population-SD analysis
from free population-SD estimation.  They are operating-characteristic
comparisons, not direct FACETS-equality tests: FACETS 4.5 uses JMLE.
"""

from __future__ import annotations

